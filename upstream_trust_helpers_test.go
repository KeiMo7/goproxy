// testCA bundles a generated CA certificate with its private key and the PEM
// form needed to register trust groups.
type testCA struct {
	cert    *x509.Certificate
	key     *ecdsa.PrivateKey
	certPEM []byte
}

func newTestCA(t testingT, commonName string) *testCA {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatalf("generate CA key: %v", err)
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		t.Fatalf("CA serial: %v", err)
	}
	template := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: commonName},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(24 * time.Hour),
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		t.Fatalf("create CA cert: %v", err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatalf("parse CA cert: %v", err)
	}
	return &testCA{
		cert:    cert,
		key:     key,
		certPEM: pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}),
	}
}

// leafSpec controls a leaf certificate generated by testCA.issue.
type leafSpec struct {
	dnsNames []string
	ips      []net.IP
	// expired makes the leaf invalid at the current time.
	expired bool
	// notYetValid makes the leaf's validity window start in the future.
	notYetValid bool
	// extraIssuer signs the leaf with a different CA to simulate an
	// unregistered private issuer.
	extraIssuer *testCA
}

func (ca *testCA) issue(t testingT, spec leafSpec) tls.Certificate {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatalf("generate leaf key: %v", err)
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		t.Fatalf("leaf serial: %v", err)
	}
	notBefore := time.Now().Add(-time.Hour)
	notAfter := time.Now().Add(24 * time.Hour)
	switch {
	case spec.expired:
		notBefore = time.Now().Add(-48 * time.Hour)
		notAfter = time.Now().Add(-24 * time.Hour)
	case spec.notYetValid:
		notBefore = time.Now().Add(24 * time.Hour)
		notAfter = time.Now().Add(48 * time.Hour)
	}
	template := &x509.Certificate{
		SerialNumber: serial,
		Subject:      pkix.Name{CommonName: firstOr(spec.dnsNames, "leaf")},
		NotBefore:    notBefore,
		NotAfter:     notAfter,
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		DNSNames:     spec.dnsNames,
		IPAddresses:  spec.ips,
	}
	issuer := ca
	issuerCert := ca.cert
	issuerKey := ca.key
	if spec.extraIssuer != nil {
		issuer = spec.extraIssuer
		issuerCert = spec.extraIssuer.cert
		issuerKey = spec.extraIssuer.key
	}
	der, err := x509.CreateCertificate(rand.Reader, template, issuerCert, &key.PublicKey, issuerKey)
	if err != nil {
		t.Fatalf("issue leaf: %v", err)
	}
	leaf, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatalf("parse leaf: %v", err)
	}
	_ = issuer
	return tls.Certificate{Certificate: [][]byte{der}, PrivateKey: key, Leaf: leaf}
}

func firstOr(names []string, fallback string) string {
	if len(names) > 0 {
		return names[0]
	}
	return fallback
}

// sniCertServer is an HTTPS server that selects its leaf certificate based
// on the SNI value, like a virtual-host TLS endpoint. Unknown SNIs get a
// fallback certificate.
type sniCertServer struct {
	server *httptest.Server
	names  chan string
}

func newSNICertServer(t *testing.T, certs map[string]tls.Certificate, fallback tls.Certificate) *sniCertServer {
	t.Helper()
	names := make(chan string, 4096)
	getCert := func(hello *tls.ClientHelloInfo) (*tls.Certificate, error) {
		select {
		case names <- hello.ServerName:
		default:
		}
		if cert, ok := certs[hello.ServerName]; ok {
			return &cert, nil
		}
		return &fallback, nil
	}
	handler := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		_, _ = w.Write([]byte("ok"))
	})
	srv := httptest.NewUnstartedServer(handler)
	srv.TLS = &tls.Config{GetCertificate: getCert}
	srv.StartTLS()
	t.Cleanup(srv.Close)
	return &sniCertServer{server: srv, names: names}
}

func (s *sniCertServer) drainNames() []string {
	var out []string
	for {
		select {
		case n := <-s.names:
			out = append(out, n)
		default:
			return out
		}
	}
}

// testingT is the subset of *testing.T the helpers rely on.
type testingT interface {
	Helper()
	Fatalf(format string, args ...any)
}
